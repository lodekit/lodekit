#!/usr/bin/env node
// Dev-time generator for the @lodekit/ui/icons name maps. Plain Node, no deps.
//
// Scans the repo for icons imported from `lucide-react` / `@lodekit/ui/icons`,
// canonicalizes to lucide's bare names, auto-matches each against the installed
// Phosphor and Tabler export lists (with a curated OVERRIDES table for the
// non-identical names), and writes the checked-in generated maps consumed by
// `src/icons/index.ts`. Idempotent; run it and commit the outputs:
//
//   node packages/ui/scripts/generate-icon-maps.mjs
//
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const UI = resolve(HERE, "..")
const REPO = resolve(UI, "..", "..")
const OUT = join(UI, "src", "icons", "generated")

// Trees scanned for icon usage (spec §3 coverage set).
const SCAN_TARGETS = [
  join(UI, "src"),
  join(REPO, "packages", "engine", "dashboard", "src"),
  join(REPO, "packages", "engine", "src", "scaffold.ts"),
  join(REPO, "root", "apps"),
]

// Non-icon named exports of lucide-react that the scan must ignore.
const NOT_ICONS = new Set(["LucideIcon", "LucideProps", "Icon", "createLucideIcon"])

// Canonical lucide name -> alternate-set export name, for the cases where the
// bare name / `Icon`-prefixed name does not auto-match. Curated by hand.
