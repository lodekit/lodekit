const HEADER = "/* generated by scripts/generate-icon-maps.mjs — do not edit */\n"

function walk(path, out) {
  let stat
  try {
    stat = statSync(path)
  } catch {
    return out
  }
  if (stat.isFile()) {
    if (/\.(ts|tsx)$/.test(path)) out.push(path)
    return out
  }
  for (const entry of readdirSync(path)) {
    if (entry === "node_modules" || entry === "dist" || entry.startsWith("."))
      continue
    walk(join(path, entry), out)
  }
  return out
}

// Collect the raw named specifiers imported from the icon modules.
function scanRawNames() {
  const files = SCAN_TARGETS.flatMap((t) => walk(t, []))
  const importRe =
    /import\s+(type\s+)?\{([^}]*)\}\s*from\s*["'](?:lucide-react|@lodekit\/ui\/icons)["']/g
  const names = new Set()
  for (const file of files) {
    const src = readFileSync(file, "utf8")
    let match
    while ((match = importRe.exec(src))) {
      if (match[1]) continue // whole `import type { ... }`
      for (let spec of match[2].split(",")) {
        spec = spec.trim()
        if (!spec || spec.startsWith("type ")) continue
        const original = spec.split(/\s+as\s+/)[0].trim()
        if (original && !NOT_ICONS.has(original)) names.add(original)
      }
    }
  }
  return names
}

async function loadExportSet(specifier) {
  return new Set(Object.keys(await import(specifier)))
}

function canonicalize(raw, lucide) {
  // Strip a trailing `Icon` when the bare name is itself a lucide icon.
  if (raw.endsWith("Icon")) {
    const bare = raw.slice(0, -4)
    if (bare && lucide.has(bare)) return bare
  }
  return raw
}

function matchPhosphor(name, phosphor) {
  const override = OVERRIDES.phosphor[name]
  if (override) return phosphor.has(override) ? override : null
  return phosphor.has(name) ? name : null
}

function matchTabler(name, tabler) {
  const override = OVERRIDES.tabler[name]
  if (override) return tabler.has(override) ? override : null
  const prefixed = "Icon" + name
  return tabler.has(prefixed) ? prefixed : null
}

// Emit `generated/<set>.ts`: named imports (only the mapped icons — the lazy
// chunk stays lean) plus a default map keyed by canonical name.
function writeSetFile(set, specifier, entries) {
  const identifiers = [...new Set(entries.map(([, id]) => id))].sort()
  const imports = identifiers
    .map((id) => `  ${id},`)
    .join("\n")
  const body = entries
    .map(([name, id]) => (name === id ? `  ${name},` : `  ${name}: ${id},`))
    .join("\n")
  const out =
    HEADER +
    `import {\n${imports}\n} from "${specifier}"\n\n` +
    `const map = {\n${body}\n}\n\nexport default map\n`
  writeFileSync(join(OUT, `${set}.ts`), out)
}

// Emit `generated/names.ts`: the lucide import block, the canonical/alias icon
// components (each wrapped via createIcon), and the CANONICAL_NAMES /
// KNOWN_UNMAPPED metadata consumed by index.ts and the coverage test.
function writeNamesFile(canonical, aliases, knownUnmapped) {
  const lucideImports = canonical
    .map((name) => `  ${name} as Lucide${name},`)
    .join("\n")
  const namesList = canonical.map((name) => `  "${name}",`).join("\n")
  const unmappedList = knownUnmapped.map((name) => `  "${name}",`).join("\n")
  const components = canonical
    .map((name) => `export const ${name} = createIcon("${name}", Lucide${name})`)
    .join("\n")
  const aliasLines = aliases
    .map(([spelling, target]) => `export const ${spelling} = ${target}`)
    .join("\n")
  const out =
    HEADER +
    `import {\n${lucideImports}\n} from "lucide-react"\n\n` +
    `import { createIcon } from "../create-icon"\n\n` +
    `export const CANONICAL_NAMES = [\n${namesList}\n] as const\n\n` +
    `export const KNOWN_UNMAPPED: readonly string[] = [\n${unmappedList}\n]\n\n` +
    `${components}\n\n${aliasLines}\n`
  writeFileSync(join(OUT, "names.ts"), out)
}

async function main() {
  const lucide = await loadExportSet("lucide-react")
  const phosphor = await loadExportSet("@phosphor-icons/react")
  const tabler = await loadExportSet("@tabler/icons-react")

  const raw = [...scanRawNames()]
  const canonicalSet = new Set()
  const aliases = [] // [spelling, canonical]
  for (const name of raw) {
    const canon = canonicalize(name, lucide)
    if (!lucide.has(canon)) {
      console.warn(`skip: ${name} (no lucide export for canonical ${canon})`)
      continue
    }
    canonicalSet.add(canon)
    if (name !== canon) aliases.push([name, canon])
  }
  const canonical = [...canonicalSet].sort()
  aliases.sort((a, b) => a[0].localeCompare(b[0]))

  const phosphorEntries = []
  const tablerEntries = []
  const knownUnmapped = []
  for (const name of canonical) {
    const ph = matchPhosphor(name, phosphor)
    const tb = matchTabler(name, tabler)
    if (ph) phosphorEntries.push([name, ph])
    if (tb) tablerEntries.push([name, tb])
    if (!ph || !tb) knownUnmapped.push(name)
  }

  writeNamesFile(canonical, aliases, knownUnmapped)
  writeSetFile("phosphor", "@phosphor-icons/react", phosphorEntries)
  writeSetFile("tabler", "@tabler/icons-react", tablerEntries)

  console.log(
    `icons: ${canonical.length} canonical, ${aliases.length} aliases, ` +
      `${phosphorEntries.length} phosphor, ${tablerEntries.length} tabler, ` +
      `${knownUnmapped.length} known-unmapped` +
      (knownUnmapped.length ? ` (${knownUnmapped.join(", ")})` : "")
  )
}

main()
