// Generates the brand asset kit in public/brand/: mark, wordmark, lockup, and
// badge, each in a paper (plum ink) and night (pale gold) variant, as SVG plus
// PNG exports. Run with `pnpm brand:assets`.
//
// Sources of truth: the jar-cloud mark is imported from
// packages/engine/src/marks.ts (MARK_BODIES.b, the default knockout style —
// never redrawn); the wordmark is M PLUS 1 Code 700 at 0.22em tracking
// (DESIGN.md §5), outlined to paths because GitHub-README SVGs cannot load
// fonts. Colors and geometry follow docs/DESIGN.md: lockup gap ≈0.6em,
// wordmark at 0.8× the mark box, chip = page fill + 1px hairline + 3px radius,
// minimum mark 16px with clear space ≥ the lid width.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";
import sharp from "sharp";
import { MARK_BODIES } from "@lodekit/engine/marks";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "../public/brand");
const FONT = path.join(here, "../node_modules/@fontsource/m-plus-1-code/files/m-plus-1-code-latin-700-normal.woff");

const INK = { paper: "#251B25", night: "#F3E0A5" };
const CHIP = {
  paper: { fill: "#F6F1E6", edge: "#CDC4AE" }, // page + hairline
  night: { fill: "#121A44", edge: "#242E63" }, // night + night-lo (the night plate's border token)
};
const TRACK = 0.22; // wordmark letter-spacing (em)
const GAP_EM = 0.6; // lockup gap, in wordmark ems
const WORDMARK_RATIO = 0.8; // wordmark font size : mark box (1.2rem : 1.5rem)
const LID = 13.98; // the jar lid's width in the 32-unit mark box — the clear-space unit

const font = opentype.parse(fs.readFileSync(FONT));
const capEm = font.tables.os2.sCapHeight / font.unitsPerEm;

const note = "generated by web/main/scripts/gen-brand-assets.mjs — regenerate there, don't edit here";

function wordmark(fontSize, x = 0, baseline = 0) {
  const opts = { kerning: true, letterSpacing: TRACK };
  const bbox = font.getPath("LODEKIT", 0, 0, fontSize, opts).getBoundingBox();
  const d = font.getPath("LODEKIT", x, baseline, fontSize, opts).toPathData(2);
  return { d, bbox };
}

const svg = (w, h, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="Lodekit"><!-- ${note} -->${body}</svg>\n`;

function markSvg(plate) {
  return svg(32, 32, `<g color="${INK[plate]}">${MARK_BODIES.b}</g>`);
}

function wordmarkSvg(plate) {
  const fontSize = 32;
  const { bbox } = wordmark(fontSize);
  const w = Math.ceil(bbox.x2 - bbox.x1);
  const h = Math.ceil(bbox.y2 - bbox.y1);
  const { d } = wordmark(fontSize, -bbox.x1, -bbox.y1);
  return svg(w, h, `<path fill="${INK[plate]}" d="${d}"/>`);
}

// mark box + gap + wordmark, cap band centered on the mark box (the lockup's
// optical cap-height alignment)
function lockupBody(plate, markBox, x, y, boxH) {
  const fontSize = markBox * WORDMARK_RATIO;
  const { bbox } = wordmark(fontSize);
  const textX = x + markBox + GAP_EM * fontSize - bbox.x1;
  const baseline = y + (boxH + capEm * fontSize) / 2;
  const { d } = wordmark(fontSize, textX, baseline);
  const w = markBox + GAP_EM * fontSize + (bbox.x2 - bbox.x1);
  const markY = y + (boxH - markBox) / 2;
  const body =
    `<g color="${INK[plate]}"><g transform="translate(${x},${markY}) scale(${markBox / 32})">${MARK_BODIES.b}</g>` +
    `<path fill="currentColor" d="${d}"/></g>`;
  return { body, w };
}

function lockupSvg(plate) {
  const { body, w } = lockupBody(plate, 32, 0, 0, 32);
  return svg(Math.ceil(w), 32, body);
}

// the lockup as a chip: 16px mark (the brand minimum) in a 30px chip so the
// clear space stays ≥ the lid width (6.99px)
function badgeSvg(plate) {
  const H = 30;
  const PAD = 9;
  const { body, w } = lockupBody(plate, 16, PAD, 0, H);
  const W = Math.ceil(PAD + w + PAD);
  const chip = CHIP[plate];
  return svg(
    W,
    H,
    `<rect x="0.5" y="0.5" width="${W - 1}" height="${H - 1}" rx="3" fill="${chip.fill}" stroke="${chip.edge}"/>${body}`,
  );
}

// Transparent by default. With `bg`, the export is an on-plate tile: `height`
// names the full canvas, the content sits centered inside clear-space padding
// (`padUnits`, in the SVG's own units), and the alpha is flattened onto the
// plate color.
async function png(svgText, outName, { height, scale, bg, padUnits = 0 }) {
  const [, w, h] = svgText.match(/width="(\d+)" height="(\d+)"/).map(Number);
  const s = height ? height / (h + 2 * padUnits) : scale;
  const img = sharp(Buffer.from(svgText), { density: 72 * s }).png();
  if (!bg) return img.toFile(path.join(OUT, outName));
  const buf = await img.toBuffer();
  const m = await sharp(buf).metadata();
  const width = Math.round((w + 2 * padUnits) * s);
  const padTop = Math.floor((height - m.height) / 2);
  const padLeft = Math.floor((width - m.width) / 2);
  await sharp(buf)
    .flatten({ background: bg })
    .extend({ top: padTop, bottom: height - m.height - padTop, left: padLeft, right: width - m.width - padLeft, background: bg })
    .toFile(path.join(OUT, outName));
}

// Transparent mark PNGs keep the 32-unit box and its native margins; on-plate
// tiles crop to the drawn ink and set its height at 3/4 of the square tile
// side. Rendered oversized and trimmed, then scaled, so the crop is exact.
async function markPng(svgText, outName, { size, bg }) {
  if (!bg) return png(svgText, outName, { height: size });
  const hi = await sharp(Buffer.from(svgText), { density: 72 * (2048 / 32) }).png().toBuffer();
  const ink = await sharp(hi).trim().toBuffer();
  const scaled = await sharp(ink).resize({ height: Math.round(size * 0.75) }).png().toBuffer();
  const m = await sharp(scaled).metadata();
  const top = Math.floor((size - m.height) / 2);
  const left = Math.floor((size - m.width) / 2);
  await sharp(scaled)
    .flatten({ background: bg })
    .extend({ top, bottom: size - m.height - top, left, right: size - m.width - left, background: bg })
    .toFile(path.join(OUT, outName));
}

fs.mkdirSync(OUT, { recursive: true });
for (const plate of ["paper", "night"]) {
  const bg = CHIP[plate].fill;
  const wordmarkPad = GAP_EM * 32; // no lid to measure against — 0.6em of the wordmark's own size
  const files = {
    [`lodekit-mark-${plate}`]: {
      text: markSvg(plate),
      render: markPng,
      pngs: [
        ["-128.png", { size: 128 }], ["-512.png", { size: 512 }],
        ["-bg-128.png", { size: 128, bg }], ["-bg-512.png", { size: 512, bg }],
      ],
    },
    [`lodekit-wordmark-${plate}`]: {
      text: wordmarkSvg(plate),
      pngs: [
        ["-h128.png", { height: 128 }], ["-h512.png", { height: 512 }],
        ["-bg-h128.png", { height: 128, bg, padUnits: wordmarkPad }], ["-bg-h512.png", { height: 512, bg, padUnits: wordmarkPad }],
      ],
    },
    [`lodekit-lockup-${plate}`]: {
      text: lockupSvg(plate),
      pngs: [
        ["-h128.png", { height: 128 }], ["-h512.png", { height: 512 }],
        ["-bg-h128.png", { height: 128, bg, padUnits: LID }], ["-bg-h512.png", { height: 512, bg, padUnits: LID }],
      ],
    },
    [`lodekit-badge-${plate}`]: { text: badgeSvg(plate), pngs: [["@2x.png", { scale: 2 }], ["@4x.png", { scale: 4 }]] },
  };
  for (const [base, { text, pngs, render = png }] of Object.entries(files)) {
    fs.writeFileSync(path.join(OUT, `${base}.svg`), text);
    for (const [suffix, size] of pngs) await render(text, base + suffix, size);
  }
}
console.log(`wrote ${fs.readdirSync(OUT).filter((f) => f.startsWith("lodekit-")).length} files to ${path.relative(process.cwd(), OUT)}`);
